/* DOM interaction smoke tests for WRHA Hub. Requires npm install --no-save jsdom@24 */
import {JSDOM,VirtualConsole} from 'jsdom';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const html=fs.readFileSync('index.html','utf8');
const vcon=new VirtualConsole();const issues=[];
vcon.on('jsdomError',e=>issues.push(String(e.message||e)));
const dom=new JSDOM(html,{url:'https://example.org/WRHA-Manual-Resource-Hub/',runScripts:'outside-only',pretendToBeVisual:true,virtualConsole:vcon});
const {window:w}=dom,{document:d}=w;
w.matchMedia=()=>({matches:true,addListener(){},removeListener(){}});w.scrollTo=()=>{};
w.HTMLElement.prototype.scrollIntoView=function(){};
for(const dialog of d.querySelectorAll('dialog')){dialog.showModal=function(){this.setAttribute('open','')};dialog.close=function(){this.removeAttribute('open');this.dispatchEvent(new w.Event('close'))};}
w.open=()=>{};
w.eval(fs.readFileSync('data.js','utf8'));
w.eval(fs.readFileSync('catalog-extra.js','utf8'));
w.eval(fs.readFileSync('app-v2.js','utf8'));
const click=q=>{const e=d.querySelector(q);assert(e,'Missing clickable element '+q);e.click();return e;};
const visible=q=>{const el=d.querySelector(q);assert(el,'Missing '+q);return el;};
assert.equal(d.querySelectorAll('.nav-button').length,7);
assert(d.querySelectorAll('#featured .manual-card').length>0);
click('[data-view="manuals"]');
assert(visible('[data-page="manuals"]').classList.contains('active'));
assert(d.querySelectorAll('#manualGrid .manual-card').length>0);
assert(d.querySelector('#manualGrid .doc-cover'));
const search=visible('#manualSearch');search.value='surveillance';search.dispatchEvent(new w.Event('input',{bubbles:true}));assert(d.getElementById('manualCount').textContent.includes('resource'));
search.value='';search.dispatchEvent(new w.Event('input',{bubbles:true}));
click('[data-view="legislation"]');
assert(visible('[data-page="legislation"]').classList.contains('active'));
assert(d.querySelectorAll('#lawGrid .manual-card').length>0);
const lawSearch=visible('#lawSearch');lawSearch.value='Public Health';lawSearch.dispatchEvent(new w.Event('input',{bubbles:true}));assert(d.querySelectorAll('#lawGrid .manual-card').length>0);
click('[data-view="facilities"]');
assert.equal(d.querySelectorAll('.parish-badge').length,13);
click('[data-mapparish="Hanover"]');
assert(d.getElementById('facilityCount').textContent.includes('Hanover'));
click('#resetMap');
click('[data-view="roles"]');
const roleSearch=visible('#roleSearch');roleSearch.value='Dental Nurse';roleSearch.dispatchEvent(new w.Event('input',{bubbles:true}));assert(d.getElementById('roleCount').textContent.includes('1 distinct'));assert(d.getElementById('rolesGrid').textContent.includes('Dental Nurse'));
click('[data-view="training"]');assert(d.querySelectorAll('[data-page="training"] .training-card').length===2);
assert(d.querySelectorAll('.social-buttons a').length===5);
assert.equal(issues.length,0,'Console errors: '+issues.join('; '));
console.log('DOM SMOKE: PASS — navigation, manual search, legislation, parish badges, 229-role directory, training, social links');
